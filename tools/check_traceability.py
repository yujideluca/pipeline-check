#!/usr/bin/env python3
"""Requirement traceability gate.

Reads the requirement IDs from docs/REQUIREMENTS.md, collects `REQ <ID>` tags from the test folders in TEST_DIRS,
and fails when a requirement has no tagged test or a tag names an unknown requirement.
Writes docs/TRACEABILITY.md (requirement -> test files) so the matrix is always current.
"""
import os, re, sys

TEST_DIRS = ["src", "tests"]
EXTENSIONS = (".py", ".kt", ".js", ".ts", ".rs")

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
req_text = open(os.path.join(root, "docs/REQUIREMENTS.md"), encoding="utf-8").read()
reqs = [(i, t) for i, t in re.findall(r"^\| ([A-Z]{2}-\d+) \| (.+?) \|", req_text, re.M)]
found = {i: [] for i, _ in reqs}
unknown = []
tag_line = re.compile(r"^\s*(?://|#|\*|/\*\*)\s*REQ ((?:[A-Z]{2}-\d+[ ,]*)+)", re.M)
for test_dir in TEST_DIRS:
    for d, _, files in os.walk(os.path.join(root, test_dir)):
        for f in files:
            if f.endswith(EXTENSIONS):
                text = open(os.path.join(d, f), encoding="utf-8").read()
                for m in tag_line.finditer(text):
                    for tag in re.findall(r"[A-Z]{2}-\d+", m.group(1)):
                        if tag not in found:
                            unknown.append(f"{f} names unknown requirement {tag}")
                        elif f not in found[tag]:
                            found[tag].append(f)

lines = ["# Traceability matrix", "", "Generated by `tools/check_traceability.py`; do not edit.", "",
         "| Requirement | Verified by |", "|---|---|"]
lines += [f"| {i} {t[:70]} | {', '.join(sorted(found[i])) or '**none**'} |" for i, t in reqs]
open(os.path.join(root, "docs/TRACEABILITY.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

missing = [i for i, _ in reqs if not found[i]]
for m in missing:
    print(f"requirement {m} has no test")
for u in unknown:
    print(u)
if missing or unknown:
    sys.exit(1)
print(f"traceability ok: {len(reqs)} requirements, all covered by tagged tests")
